import { test } from '@e2e-dev/web'
import { expect } from 'e2e'

test('installs packed-SDK summary and chat projects, pairs, restarts, disables and uninstalls through the UI', async ({ app, screen, browser }) => {
  const base = app.baseUrl!
  const control = new URL(base); control.port = String(Number(control.port) + 1)
  const fixture = async (path = '/', data?: unknown) => {
    const response = await fetch(new URL(path, control), data === undefined ? {} : { method: 'POST', body: JSON.stringify(data) })
    if (!response.ok) throw Error(await response.text())
    return response.json()
  }
  const initial = await fixture()
  const install = async (path: string, name: string) => {
    await app.open('/settings/global/extensions')
    await screen.getByLabel('Extension folder or package').fill(path)
    await screen.getByRole('button', 'Preview install').tap()
    await expect(screen.getByRole('region', 'Installation preview')).toBeVisible()
    await screen.getByRole('button', 'Approve and install').tap()
    const row = screen.getByRole('listitem', name)
    await row.getByRole('button', 'Enable', { exact: true }).tap()
    await screen.getByRole('button', 'Approve and enable').tap()
    await expect(row.getByRole('button', 'Disable', { exact: true })).toBeVisible()
  }
  await install(initial.summary, 'Project summary')
  await screen.getByRole('region', 'Project summary').getByRole('button', 'Refresh summary', { exact: true }).tap()
  await fixture('/crash-summary', {})
  const summaryRow = screen.getByRole('listitem', 'Project summary')
  await summaryRow.getByRole('button', 'Review and retry', { exact: true }).tap()
  await screen.getByRole('button', 'Approve and enable').tap()
  await expect(summaryRow.getByRole('button', 'Review and retry', { exact: true })).not.toBeVisible()
  await fixture('/update-summary', {})
  await summaryRow.getByRole('button', 'Reload / update').tap()
  await expect(screen.getByText('Added permissions: task.create', { exact: true })).toBeVisible()
  await screen.getByRole('button', 'Cancel install').tap()
  await screen.getByRole('region', 'Project summary').getByRole('button', 'Refresh summary', { exact: true }).tap()
  await install(initial.chat, 'Mattermost')
  await app.open('/p/default/settings/integrations?integration=open-mercato.mattermost%2Fchat')
  await screen.getByRole('button', 'Connect Mattermost', { exact: true }).tap()
  await screen.getByRole('button', /Notifications and task control/).tap()
  await screen.getByLabel('Mattermost HTTPS server URL').fill('https://mattermost.example')
  await screen.getByLabel('Dedicated bot access token').fill('fixture-token')
  await screen.getByRole('checkbox', 'This bot is dedicated to this Cezar project.').check()
  await screen.getByRole('button', 'Continue', { exact: true }).tap()
  await expect(screen.getByLabel('Setup command')).toBeVisible()
  const command = await screen.getByLabel('Setup command').inputValue()
  await fixture('/message', { text: command })
  await expect(screen.getByRole('checkbox', 'Enable task control for this private chat')).toBeVisible()
  await screen.getByRole('checkbox', 'Enable task control for this private chat').check()
  await screen.getByRole('button', 'Activate notifications and task control').tap()
  await expect(screen.getByText(/task control is enabled/)).toBeVisible()
  await screen.getByRole('button', 'Done', { exact: true }).tap()
  expect((await fixture()).inbound.grants).toHaveLength(1)
  expect((await fixture()).sent.some((message: { message: string }) => message.message.includes('Test message'))).toBe(true)
  await fixture('/restart', {})
  await browser.reload()
  await expect.poll(async () => (await fixture()).inbound?.grants.length).toBe(1)
  await app.open('/settings/global/extensions')
  const chat = screen.getByRole('listitem', 'Mattermost')
  await chat.getByRole('button', 'Disable', { exact: true }).tap()
  await expect(chat.getByRole('button', 'Enable', { exact: true })).toBeVisible()
  expect((await fixture()).inbound).toBeUndefined()
  await screen.getByRole('region', 'Project summary').getByRole('button', 'Refresh summary', { exact: true }).tap()
  await chat.getByRole('button', 'Uninstall', { exact: true }).tap()
  await screen.getByRole('button', 'Uninstall and keep data').tap()
  await expect(chat).not.toBeVisible()
  const summary = screen.getByRole('listitem', 'Project summary')
  await summary.getByRole('button', 'Disable', { exact: true }).tap()
  await expect(summary.getByRole('button', 'Enable', { exact: true })).toBeVisible()
  await summary.getByRole('button', 'Uninstall', { exact: true }).tap()
  await screen.getByRole('button', 'Uninstall and keep data').tap()
  await expect(summary).not.toBeVisible()
  expect((await fixture()).runs).toHaveLength(0)
})
